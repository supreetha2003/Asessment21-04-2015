package firstassesment;

public class Patterns {

	public static void main(String[] args) {
		for(int i=0;i<=0;i++) {
			System.out.println("*");
			for(int j=3;j<=0;j++);
			System.out.println("***");
			for(int k=0;k<=0;k++) {
				System.out.println("******");
			}
			
		}
	}
}
		
			

